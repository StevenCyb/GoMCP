func TestPromptAndCompletionRegistration(t *testing.T) {
	p := base()
	p.Resources = []project.Resource{{Common: project.Common{Func: fn("Read"), Name: "Read"}, URI: "note:///{id}", Template: true}}
	p.Prompts = []project.Prompt{{Common: project.Common{Func: fn("Sum"), Name: "summarize", Title: "Sum", Description: "d"}}}
	complete := fn("CompleteID")
	p.Completions = []project.Completion{
		{Prompt: "summarize", Arg: "style", Values: []string{"short", "bullets"}},
		{Prompt: "summarize", Arg: "id", Func: &complete},
		{Template: "note:///{id}", Arg: "id", Func: &complete},
	}
	src := gen(t, p)

	assert.Contains(t, src, "mcp.AddPrompt(srv, mcp.PromptDef{")
	assert.Contains(t, src, `Name: "summarize"`)
	assert.Contains(t, src, "}, api.Sum)")
	assert.Contains(t, src, `srv.AddPromptCompletion("summarize", "style", mcp.Values("short", "bullets"))`)
	assert.Contains(t, src, `srv.AddPromptCompletion("summarize", "id", api.CompleteID)`)
	assert.Contains(t, src, `srv.AddResourceCompletion("note:///{id}", "id", api.CompleteID)`)

	// completions come after the features they refer to
	assert.Less(t, indexOf(src, "mcp.AddPrompt("), indexOf(src, "srv.AddPromptCompletion("))
	assert.Less(t, indexOf(src, "mcp.AddResource("), indexOf(src, "srv.AddResourceCompletion("))
}

func indexOf(s, sub string) int {
	for i := 0; i+len(sub) <= len(s); i++ {
		if s[i:i+len(sub)] == sub {
			return i
		}
	}
	return -1
}

