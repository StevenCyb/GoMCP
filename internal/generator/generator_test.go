const importAPI = "example.com/app"

func fn(name string) project.FuncRef {
	return project.FuncRef{Pkg: "api", ImportPath: importAPI, Name: name}
}

func gen(t *testing.T, p *project.Project) string {
	t.Helper()
	src, err := generator.Generate(p)
	require.NoError(t, err)

	_, err = parser.ParseFile(token.NewFileSet(), "main.go", src, parser.AllErrors)
	require.NoError(t, err, "generated code must be valid Go:\n%s", src)
	formatted, err := format.Source(src)
	require.NoError(t, err)
	assert.Equal(t, string(formatted), string(src), "generated code is gofmt formatted")
	return string(src)
}

func base() *project.Project {
	return &project.Project{
		Module:    project.Module{Path: "example.com/app"},
		Server:    project.Server{Name: "notes", Version: "1.0.0"},
		Transport: project.Transport{Endpoint: "/mcp"},
	}
}

func TestCacheScopeDefaultsPrivate(t *testing.T) {
	for scope, want := range map[string]string{"": "CachePrivate", "private": "CachePrivate", "public": "CachePublic"} {
		p := base()
		p.Transport.CacheTTL, p.Transport.CacheScope = "5m", scope
		assert.Contains(t, gen(t, p), `mcp.WithCache(mustDuration("5m"), mcp.`+want+`)`, scope)
	}
}

